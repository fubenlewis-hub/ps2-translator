def to_jis_encodable(text, report=None):
    """
    把文本转换为 cp932 可编码的形式。
    report: 可选 dict，记录无法映射的字符 {char: count}。
    返回转换后的字符串。
    """
    if not text:
        return text
    # 第一遍：多字词整词替换（避免单字误命中）
    words = sorted([(k, v) for k, v in S2J_COMMON.items() if len(k) >= 2],
                   key=lambda x: -len(x[0]))
    out = text
    for k, v in words:
        out = out.replace(k, v)
    # 第二遍：逐字符
    result = []
    for ch in out:
        if _try_encode(ch):
            result.append(ch)
            continue
        v = S2J_COMMON.get(ch)          # 单字表
        if v and _try_encode(v):
            result.append(v)
            continue
        if _cc is not None:
            t = _cc.convert(ch)
            if _try_encode(t):
                result.append(t)
                continue
        if report is not None:
            report[ch] = report.get(ch, 0) + 1
        result.append("・")
    return "".join(result)


def _try_encode(ch):
    try:
        ch.encode("cp932")
        return True
    except UnicodeEncodeError:
        return False


def convert_entries(entries, progress_cb=None):
    """
    批量把条目的 translation 转换为 JIS 可编码文本。
    entries: list[TextEntry]（就地修改 translation_jis 字段）
    返回未映射字符报告 {char: count}。
    """
    report = {}
    for e in entries:
        if not e.translation:
            continue
        e.translation_jis = to_jis_encodable(e.translation, report)
        if progress_cb:
            progress_cb()
    return report
